HGARC9 = HGARC9 or {}

HGARC9.Config = {
	-- Категория в спавн-меню
	Category = "[HG] ARC9",

	-- Префикс класса прокси-оружия: arc9_xxx -> hg_arc9_xxx
	ProxyPrefix = "hg_",

	-- Автоматически заменять ARC9-пушки, попавшие к игроку (Give, лут, инвентарь),
	-- на их Homigrad-версию. Если false - ARC9-оригиналы остаются как есть (будут глючить).
	AutoConvertPickup = true,

	-- Множитель урона ARC9 (DamageMax) -> Primary.Damage хомиграда.
	-- Для сравнения в хомиграде: Glock = 25, AKM = 45.
	DamageScale = 1.1,

	-- То же для дроби (Num > 1): в ARC9 урон считается за дробинку и он маленький,
	-- в хомиграде M590 = 35 за дробинку.
	PelletDamageScale = 3.0,

	-- Множитель разброса (ARC9 Spread -> Primary.Cone)
	SpreadScale = 0.5,

	-- Множитель вертикальной/горизонтальной отдачи камеры (ARC9 RecoilUp/RecoilSide)
	RecoilScale = 0.6,

	-- v2: автоматическая калибровка позы оружия в руке.
	-- Хомиград ведёт руку по петле обратной связи (salat_base:ApplyAnim подтягивает localAngle к углу
	-- ствола каждый кадр). У моделей ARC9 эта петля не сходится: оружие дёргается при ходьбе
	-- и «плывёт» набок в покое. При AutoCalibrate аддон считает нужный localAngle один раз по геометрии
	-- модели и фиксирует его, поэтому поза стабильна. Если что-то пошло не так - поставь false
	-- (вернётся поведение v1 с LegacyRollFix).
	AutoCalibrate = true,

	-- Определять направление ствола модели по аттачменту "muzzle" (иначе считается +X).
	-- Если у конкретной пушки определилось неверно - задай hgAxis в Overrides.
	AutoAxis = true,

	-- Дополнительный крен оружия относительно взгляда (градусы). 0 = оружие стоит ровно.
	-- Для одной пушки - hgRoll в Overrides или hg_arc9_t_rf в режиме подгонки.
	RollFix = 0,

	-- Только для AutoCalibrate = false: старая компенсация крена через addAng (v1).
	LegacyRollFix = 90,

	-- v2.2: обычный игрок на ногах стреляет ТОЧНО ПО ВЗГЛЯДУ (EyeAngles), а не по направлению, посчитанному
	-- из костей. На сервере кости/кэш моделей расходились с клиентскими, и пули уходили вправо.
	-- Точка вылета - дуло модели; в фейке (рэгдолл) направление по-прежнему по модели. false = поведение v2.
	EyeAim = true,

	-- Если дуло по костям дальше этого расстояния от глаз (битые кости сервера) - берётся запасная точка от глаз.
	EyeAimMaxDist = 90,

	-- v2.4: высота камеры при ПКМ по верху габарита модели. ВЫКЛЮЧЕНО в v2.5: давало камеру слишком высоко (оружие уходило
	-- вниз на экране). Камера ВЫШЕ = оружие на экране НИЖЕ. По умолчанию высота берётся из таблицы по типу оружия.
	AutoSightHeight = false,
	AutoSightHeightMul = 1.0,

	-- v2.3: клиент присылает серверу положение своего дула относительно глаз, сервер стреляет из этой точки
	-- (серверные кости рук не совпадают с клиентскими). false = точка по серверным костям.
	ClientMuzzle = true,

	-- v2.3: пуля идёт из дула в точку, куда смотрит перекрестие (при ПКМ - камера): без бокового смещения на любой
	-- дистанции. false = пуля параллельна взгляду.
	Converge = true,

	-- v2.2: камера прицеливания (ПКМ) ставится на линию ствола в точке, ближайшей к голове, + SightOfs
	-- (x вперёд, y влево, z вверх; 0,0,0 = пуля в центр экрана). Глубина камеры больше не зависит от размеров
	-- модели. false = старая схема v2 (от дула, SightPos). Пушки с SightPos в Overrides всегда по старой схеме.
	AutoSight = true,

	-- v2.6.2: играть оригинальную вспышку выстрела ARC9 (MuzzleParticle / MuzzleEffect источника) в дуле прокси-оружия.
	MuzzleFlash = true,

	-- Писать в консоль подробности конвертации каждого оружия
	Debug = false,
}

